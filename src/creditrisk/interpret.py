"""Scorecard points table and LightGBM TreeSHAP importance.

Usage:  py -m creditrisk.interpret
Reads:  data/processed/model_table.parquet, artifacts/<set>/{scorecard.joblib, lgbm.joblib, split.parquet}
Writes: reports/<set>/scorecard_table.csv, reports/<set>/lgbm_shap_importance.csv, reports/scorecard_points.md,
        reports/figures/fig6_scorecard_points.png, reports/figures/fig7_lgbm_shap.png

Points scaling comes from configs/project.yaml (points): score = offset + factor x ln(good:bad odds), higher score =
lower risk. Points describe the raw logistic model, before Platt recalibration. Bin counts and default rates are
development-set values. SHAP values are LightGBM's built-in TreeSHAP contributions (log-odds) on the test set.
"""
import argparse

import joblib
import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from creditrisk.config import common_args, load_config, project_paths
from creditrisk.features import lgbm_frame
from creditrisk.scoring import (
    points_range_by_feature,
    points_scale,
    scorecard_table,
)

FS = {"full": "Full: origination + behaviour", "origination": "Origination only"}
SURF, INK, INK2, MUTED, GRID, BLUE, ORANGE = (
    "#fcfcfb", "#0b0b0b", "#52514e", "#898781", "#e1e0d9", "#2a78d6", "#eb6834")
STYLE = {
    "font.family": "sans-serif", "font.sans-serif": ["DejaVu Sans"], "figure.facecolor": SURF,
    "axes.facecolor": SURF, "savefig.facecolor": SURF, "axes.edgecolor": GRID, "axes.labelcolor": INK2,
    "xtick.color": MUTED, "ytick.color": MUTED, "text.color": INK, "axes.spines.top": False,
    "axes.spines.right": False, "axes.grid": True, "grid.color": GRID, "grid.linewidth": 0.6, "axes.axisbelow": True,
}


def md(df):
    lines = ["| " + " | ".join(df.columns) + " |", "|" + "---|" * len(df.columns)]
    return "\n".join(lines + ["| " + " | ".join(map(str, r)) + " |" for r in df.to_numpy()])


def shap_importance(lgbm_bundle, test):
    X = lgbm_frame(test, lgbm_bundle["spec"], lgbm_bundle["levels"])
    contrib = lgbm_bundle["model"].booster_.predict(X, pred_contrib=True)
    assert contrib.shape[1] == X.shape[1] + 1
    s = pd.DataFrame({"feature": X.columns, "mean_abs_shap": np.abs(contrib[:, :-1]).mean(axis=0)})
    s["share_of_total"] = s.mean_abs_shap / s.mean_abs_shap.sum()
    return s.sort_values("mean_abs_shap", ascending=False).reset_index(drop=True)


def bar_panel(data, top, color, title, xlabel, path, fmt):
    fig, axes = plt.subplots(1, 2, figsize=(11, 5))
    for ax, fs in zip(axes, FS):
        d = data[fs].head(top)[::-1]
        labels, vals = (d.index, d.values) if isinstance(d, pd.Series) else (d.feature, d.mean_abs_shap.values)
        ax.barh(labels, vals, color=color, height=0.65)
        for i, v in enumerate(vals):
            ax.text(v, i, " " + fmt(v), va="center", fontsize=8, color=INK2)
        ax.set_title(FS[fs], loc="left", fontsize=11)
        ax.set_xlabel(xlabel)
        ax.set_xlim(0, max(vals) * 1.18)
        ax.tick_params(axis="y", labelsize=8)
    fig.suptitle(title, x=0.01, ha="left", fontsize=12)
    fig.tight_layout()
    fig.savefig(path, dpi=200)
    plt.close(fig)


def run(cfg, log=print):
    paths = project_paths(cfg)
    art, rep = paths["artifacts"], paths["reports"]
    fig_dir = rep / "figures"
    fig_dir.mkdir(parents=True, exist_ok=True)
    plt.rcParams.update(STYLE)
    pts = cfg["points"]
    scale = points_scale(pts["base_score"], pts["base_odds"], pts["pdo"])

    df = pd.read_parquet(paths["processed"] / "model_table.parquet")
    tables, ranges, shap_tabs = {}, {}, {}
    for fs in FS:
        split = pd.read_parquet(art / fs / "split.parquet").set_index("loan_id").split
        dev = df[df.loan_id.map(split) == "dev"].reset_index(drop=True)
        test = df[df.loan_id.map(split) == "test"].reset_index(drop=True)
        sc = joblib.load(art / fs / "scorecard.joblib")
        t = scorecard_table(sc["model"], sc["spec"], dev, scale)
        t.to_csv(rep / fs / "scorecard_table.csv", index=False)
        tables[fs] = t
        ranges[fs] = points_range_by_feature(t, pts["min_bin_loans"])
        shap_tabs[fs] = shap_importance(joblib.load(art / fs / "lgbm.joblib"), test)
        shap_tabs[fs].to_csv(rep / fs / "lgbm_shap_importance.csv", index=False)

    top = pts["top_features"]
    bar_panel(ranges, top, BLUE,
              f"Scorecard: points range per feature (bins with at least {pts['min_bin_loans']} development loans)",
              "Points between the lowest- and highest-risk bin", fig_dir / "fig6_scorecard_points.png",
              lambda v: f"{v:.0f}")
    bar_panel(shap_tabs, top, ORANGE, "LightGBM challenger: mean |SHAP| on the test set (log-odds)",
              "Mean absolute contribution to log-odds of default", fig_dir / "fig7_lgbm_shap.png",
              lambda v: f"{v:.2f}")

    lines = ["# Scorecard points (generated by interpret.py)\n",
             f"Base score {pts['base_score']} at {pts['base_odds']}:1 good:bad odds, {pts['pdo']} points to double the "
             "odds. Score = base points + sum of bin points; higher = lower risk. "
             "Counts and default rates are development-set values.\n"]
    for fs, t in tables.items():
        lines += [f"## {FS[fs]}\n", f"Base points: {t.points.iloc[0]:.0f}\n"]
        for f, g in t[t.feature != "BASE"].groupby("feature", sort=False):
            if len(g) > 12:
                lines.append(f"**{f}**: {len(g)} levels, see `reports/{fs}/scorecard_table.csv`.\n")
                continue
            g = g.assign(points=g.points.round(0).astype(int),
                         default_rate_dev=g.default_rate_dev.map(lambda v: f"{v:.2%}"))
            lines += [f"**{f}**\n", md(g[["bin", "points", "loans_dev", "default_rate_dev"]]), ""]
    (rep / "scorecard_points.md").write_text("\n".join(lines))

    for fs in FS:
        log(f"\n{FS[fs]}")
        log(f"scorecard points range (top 8): {ranges[fs].head(8).round(0).astype(int).to_dict()}")
        shap8 = shap_tabs[fs].head(8).set_index("feature").mean_abs_shap.round(3).to_dict()
        log(f"LightGBM mean |SHAP| (top 8): {shap8}")
    log("\nWrote scorecard tables, SHAP tables, reports/scorecard_points.md and figures 6-7")


def main(argv=None):
    ap = common_args(argparse.ArgumentParser(description=__doc__.splitlines()[0]))
    run(load_config(ap.parse_args(argv).config))


if __name__ == "__main__":
    main()
